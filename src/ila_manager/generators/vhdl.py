"""VHDL direct entity port-map instantiation generator."""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

from ila_manager.models import Ila, Signal
from ila_manager.selection import resolve_selection


def generate_vhdl(
    ila: Ila,
    signals: Optional[List[Signal]] = None,
) -> str:
    """Generate VHDL instantiation snippet for an ILA core.

    - Uses direct entity instantiation: u_<ila_name> : entity work.<ila_name>
    - Single bit probes use probeN(0) => onebitsignal; syntax
    - Generates declarations and assignments for intermediate signals (e.g. integer)
    """
    sig_map: Dict[str, Signal] = {s.name: s for s in (signals or [])}
    ip_name = ila.name or "ila_0"
    inst_name = f"u_{ip_name}"

    intermediate_decls: List[str] = []
    intermediate_assigns: List[str] = []
    port_associations: List[Tuple[str, str, str]] = []  # (lhs, rhs, comment)

    # Clock port
    port_associations.append(("clk", ila.clock or "clk", ""))

    for idx, probe in enumerate(ila.probes):
        if not probe.mapping:
            port_associations.append(
                (f"-- probe{idx}", "<unmapped>", "Unmapped probe")
            )
            continue

        sig_name = probe.mapping.signal
        sig = sig_map.get(sig_name)

        if sig is None:
            # Fallback if signal object not in scope
            is_single = (probe.width == 1)
            lhs = f"probe{idx}(0)" if is_single else f"probe{idx}"
            port_associations.append((lhs, sig_name, "Signal not in current scope"))
            continue

        resolved = resolve_selection(probe.mapping, sig, target_lang="vhdl")

        if resolved.needs_intermediate:
            inter_sig = f"ila_{ip_name}_p{idx}"
            intermediate_decls.append(
                f"signal {inter_sig} : {resolved.intermediate_type};"
            )
            intermediate_assigns.append(
                f"{inter_sig} <= {resolved.intermediate_assign};"
            )
            lhs = f"probe{idx}(0)" if resolved.is_single_bit else f"probe{idx}"
            port_associations.append((lhs, inter_sig, f"Converted from {sig_name}"))
        else:
            # Normal connection
            lhs = f"probe{idx}(0)" if resolved.is_single_bit else f"probe{idx}"
            port_associations.append((lhs, resolved.vhdl_expr, ""))

    # Format output
    lines: List[str] = []
    lines.append("-- ==============================================================================")
    lines.append(f"-- ILA Instantiation: {inst_name} ({ip_name})")
    lines.append("-- Generated by ILA Manager v0.1.0")
    lines.append("-- Direct entity instantiation — no component declaration required")
    lines.append("-- ==============================================================================")

    # Intermediate declarations block if needed
    if intermediate_decls:
        lines.append("")
        lines.append("-- [Place in architecture declarative region (before 'begin')]")
        for decl in intermediate_decls:
            lines.append(decl)
        lines.append("")
        lines.append("-- [Place in architecture statement region (after 'begin')]")
        for assign in intermediate_assigns:
            lines.append(assign)

    lines.append("")
    lines.append(f"{inst_name} : entity work.{ip_name}")
    lines.append("    port map (")

    # Align port map arrows
    max_lhs_len = max(len(lhs) for lhs, _, _ in port_associations) if port_associations else 8

    total = len(port_associations)
    for i, (lhs, rhs, cmt) in enumerate(port_associations):
        is_last = (i == total - 1)
        sep = "" if is_last else ","

        if lhs.startswith("--"):
            lines.append(f"        {lhs:<{max_lhs_len}} => {rhs}{sep}")
        else:
            cmt_str = f"  -- {cmt}" if cmt else ""
            lines.append(f"        {lhs:<{max_lhs_len}} => {rhs}{sep}{cmt_str}")

    lines.append("    );")
    return "\n".join(lines) + "\n"
