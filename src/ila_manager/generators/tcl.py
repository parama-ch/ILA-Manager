"""Vivado TCL script generator for ILA IP core creation and update."""

from __future__ import annotations

from typing import Dict, List

from ila_manager.models import Ila, ProbeType

TYPE_NAME_TO_INT: Dict[ProbeType, int] = {
    "DATA_AND_TRIGGER": 0,
    "DATA": 1,
    "TRIGGER": 2,
}


def generate_tcl(ila: Ila) -> str:
    """Generate a smart self-checking Vivado TCL script to create or update an ILA core."""
    lines: List[str] = []
    num_probes = len(ila.probes)
    ip_name = ila.name or "ila_0"

    lines.append("# ==============================================================================")
    lines.append(f"# Vivado ILA Configuration Script: {ip_name}")
    lines.append("# Generated by ILA Manager v0.1.0")
    lines.append(f"# Total Probes: {num_probes} | Pipe Stages: {ila.pipe_stages} | Depth: {ila.data_depth}")
    lines.append("# ==============================================================================")
    lines.append("")
    lines.append(f"set ila_name \"{ip_name}\"")
    lines.append("")

    # Self-checking existence guard
    dir_opt = f" -dir \"{ila.ip_dir}\"" if ila.ip_dir else ""
    lines.append("# Check if ILA IP already exists in the project; if not, create it")
    lines.append("if {[llength [get_ips -quiet $ila_name]] == 0} {")
    lines.append("    puts \"INFO: [ILA-Manager] Creating IP core '$ila_name'...\"")
    lines.append(f"    create_ip -name ila -vendor xilinx.com -library ip -module_name $ila_name{dir_opt}")
    lines.append("} else {")
    lines.append("    puts \"INFO: [ILA-Manager] Updating existing IP core '$ila_name'...\"")
    lines.append("}")
    lines.append("")

    # Property configuration list
    lines.append("# Apply ILA core properties")
    lines.append("set_property -dict [list \\")
    lines.append(f"    CONFIG.C_NUM_OF_PROBES      {{{max(1, num_probes)}}} \\")
    lines.append(f"    CONFIG.C_INPUT_PIPE_STAGES  {{{ila.pipe_stages}}} \\")
    lines.append(f"    CONFIG.C_DATA_DEPTH         {{{ila.data_depth}}} \\")
    lines.append(f"    CONFIG.C_EN_STRG_QUAL       {{{1 if ila.strg_qual else 0}}} \\")

    if ila.same_mu:
        lines.append("    CONFIG.ALL_PROBE_SAME_MU    {true} \\")
        lines.append(f"    CONFIG.ALL_PROBE_SAME_MU_CNT {{{ila.same_mu_cnt}}} \\")
    else:
        lines.append("    CONFIG.ALL_PROBE_SAME_MU    {false} \\")

    # Per-probe properties
    for idx, probe in enumerate(ila.probes):
        width = max(1, probe.width)
        type_code = TYPE_NAME_TO_INT.get(probe.probe_type, 0)
        line = f"    CONFIG.C_PROBE{idx}_WIDTH {{{width}}}  CONFIG.C_PROBE{idx}_TYPE {{{type_code}}}"
        if not ila.same_mu:
            line += f"  CONFIG.C_PROBE{idx}_MU_CNT {{{probe.mu_cnt}}}"
        line += " \\"
        lines.append(line)

    lines.append("] [get_ips $ila_name]")
    lines.append("")

    # Generate target products
    lines.append("# Generate output products for synthesis and implementation")
    lines.append("puts \"INFO: [ILA-Manager] Generating target output products for '$ila_name'...\"")
    lines.append("generate_target all [get_files [get_property IP_FILE [get_ips $ila_name]]]")
    lines.append("")

    # Optional Out-Of-Context (OOC) synthesis run
    if ila.run_ooc_synth:
        lines.append("# Launch Out-of-Context (OOC) synthesis run for the ILA IP")
        lines.append("if {[llength [get_runs -quiet ${ila_name}_synth_1]] > 0} {")
        lines.append("    reset_run ${ila_name}_synth_1")
        lines.append("} else {")
        lines.append("    catch { create_ip_run [get_ips $ila_name] }")
        lines.append("}")
        lines.append("catch { launch_runs ${ila_name}_synth_1 -jobs 4 }")
        lines.append("")

    lines.append("puts \"SUCCESS: [ILA-Manager] ILA core '$ila_name' configured successfully!\"")
    return "\n".join(lines) + "\n"
