"""Verilog / SystemVerilog named port-map instantiation generator."""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

from ila_manager.models import Ila, Signal
from ila_manager.selection import resolve_selection


def generate_verilog(
    ila: Ila,
    signals: Optional[List[Signal]] = None,
) -> str:
    """Generate Verilog / SystemVerilog named instantiation for an ILA core."""
    sig_map: Dict[str, Signal] = {s.name: s for s in (signals or [])}
    ip_name = ila.name or "ila_0"
    inst_name = f"u_{ip_name}"

    port_associations: List[Tuple[str, str, str]] = []  # (port, expr, comment)
    port_associations.append(("clk", ila.clock or "clk", ""))

    for idx, probe in enumerate(ila.probes):
        port_name = f"probe{idx}"
        if not probe.mapping:
            port_associations.append(
                (f"/* .{port_name}", "<unmapped> */", "Unmapped probe")
            )
            continue

        sig_name = probe.mapping.signal
        sig = sig_map.get(sig_name)

        if sig is None:
            port_associations.append((port_name, sig_name, "Signal not in current scope"))
            continue

        resolved = resolve_selection(probe.mapping, sig, target_lang="verilog")
        port_associations.append((port_name, resolved.verilog_expr, ""))

    lines: List[str] = []
    lines.append("// ==============================================================================")
    lines.append(f"// ILA Instantiation: {inst_name} ({ip_name})")
    lines.append("// Generated by ILA Manager v0.1.0")
    lines.append("// ==============================================================================")
    lines.append("")
    lines.append(f"{ip_name} {inst_name} (")

    max_port_len = max(len(p) for p, _, _ in port_associations) if port_associations else 6
    total = len(port_associations)

    for i, (p, expr, cmt) in enumerate(port_associations):
        is_last = (i == total - 1)
        sep = "" if is_last else ","

        if p.startswith("/*"):
            lines.append(f"    {p}({expr}){sep}")
        else:
            cmt_str = f"  // {cmt}" if cmt else ""
            lines.append(f"    .{p:<{max_port_len}} ({expr}){sep}{cmt_str}")

    lines.append(");")
    return "\n".join(lines) + "\n"
